#!/usr/bin/env bash
# 당일 아침 1회 실행: BACKLOG.md의 18개 이슈를 일괄 생성 + assign
# 사용법: bash scripts/seed-issues.sh <주영아이디> <승빈아이디> <연성아이디>
set -euo pipefail
JY="${1:?주영 아이디}"; SB="${2:?승빈 아이디}"; YS="${3:?연성 아이디}"

mk() { gh issue create --title "$1" --assignee "$2" --body "$3" >/dev/null && echo "OK: $1"; }

mk "[A1] 프로젝트 뼈대 + smoke.sh 데모 시나리오" "$JY" "스택 초기화. / 화면이 뜨면 통과하도록 scripts/smoke.sh TODO를 채운다(사람 커밋 예외). 완료: bash scripts/smoke.sh → SMOKE OK"
mk "[A2] Vercel 연결 — main 자동 배포" "$JY" "main 머지마다 자동 배포. 완료: 배포 URL에서 A1 화면 확인. 배포 URL을 README에 기록"
mk "[A3] 데이터 수집 스크립트" "$JY" "시간표 CSV(15042241, cp949)·화물역(15042207)·운행횟수(15068417/20) 로드 + 수송통계 API 클라이언트. 키는 .env(커밋 금지). 완료: data/ 정규화 JSON"
mk "[B1] 열차별 역 시퀀스 복원" "$SB" "(열차번호,운행요일) 단위 순서 정렬. 자정 넘김 처리. 완료: 샘플 3개 열차 수작업 대조 일치"
mk "[B2] 역간 소요·체류시간 계산" "$SB" "정차사유(대피/교행/화물취급/승무원교대)별 체류 집계. B1 의존"
mk "[B3] X-factor 계산" "$SB" "총 소요시간 ÷ 순수 주행시간. 구간×시간대 집계 테이블 출력. B2 의존"
mk "[B4] 히트맵 UI" "$JY" "구간×시간대 히트맵. 셀 클릭 → 체류 사유 분해 상세. B3 의존"
mk "[B5] 여객 경합 오버레이" "$SB" "여객 다이어(15125762)를 같은 축에 얹어 경합 밀도 표시. B4 의존"
mk "[C1] 역별 순흐름 계산" "$SB" "수송통계 API 기준 유입−유출. A3 의존"
mk "[C2] 불균형 지수 랭킹" "$SB" "방향별 불균형 상위 구간. C1 의존"
mk "[C3] 복화 후보 Top 10 UI" "$JY" "지도/리스트 + 오봉–부산신항 클로즈업 프리셋. C2 의존"
mk "[C4] 층3 대조(보조)" "$SB" "KTDB 도로 물량 ↔ 불균형 방향 매칭. KTDB 원본 커밋 금지, 집계 결과만"
mk "[D1] AI 원인 해석" "$YS" "진단 수치 입력 → 원인 해석 생성. 근거 수치 인용 필수. B3 의존"
mk "[D2] 부서별 문서 생성 3종" "$YS" "같은 진단 → 물류본부(슬롯 협상)/영업(구간 제안)/기획(투자 카드). D1 의존"
mk "[D3] 자연어 질의" "$SB" "\"구미에서 부산 주 3회\" → 구간 진단 요약 + 대안 시간대"
mk "[D4] AI 되먹임 — 가설 클릭 → 히트맵 필터" "$JY" "D1 출력의 구간 태그 클릭 시 B4 필터 변경. 제9조 '단순 출력 나열' 방어 장면"
mk "[E1] 시연 영상·제출물 정리" "$YS" "접속 링크 + GitHub 링크 + 영상. 오후에 착수"
mk "[E2] README" "$JY" "한 줄 소개·실행법·데이터 출처(공공데이터 4종 + 멘토링 슬라이드)"

echo "18개 생성 완료. UI 이슈(B4·C3·D4)는 주영에게 가 있음 — 연성은 발표 고정."
