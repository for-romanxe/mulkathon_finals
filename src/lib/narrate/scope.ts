// D4(#46): 함수로 답할 수 없는 질문은 지어내지 말고 떨어뜨린다.
//
// 두 종류를 구분한다.
//  (1) 구조적 범위 밖 — 우리가 애초에 만들지 않은 기능(예약·배차·실시간 추적).
//      데이터를 아무리 뒤져도 답이 없다. 도구를 부를 필요조차 없으므로 여기서 끊는다.
//  (2) 데이터에 없는 구간 — 기능은 있는데 그 값이 없는 경우. 이건 도구가 found:false로
//      답하고 라우팅 프롬프트가 처리한다. 여기서 손대지 않는다.
//
// (1)을 LLM 판단에 맡기면 "아마 이 정도일 겁니다"가 새어 나온다. 코드로 끊는 이유다.

export type OutOfScope = {
  category: "reservation" | "realtime" | "tariff" | "raw-data";
  reason: string;
  /** 대신 답할 수 있는 것. 거절만 하고 끝내면 화주 미팅에서 쓸 수 없다. */
  instead: string;
};

const RULES: Array<OutOfScope & { patterns: RegExp[] }> = [
  {
    category: "reservation",
    // `신청` 단독으로 잡지 않는다 — "철도 전환 신청 시 사회적 편익은?"은 편익 질문이다.
    // 무엇을 신청하는지가 운송·배차일 때만 범위 밖이다.
    patterns: [
      /예약/,
      /배차/,
      /(운송|운반|배송|수송|화물|화차|열차).*신청/,
      /신청.*(하려|할게|할까|해주|가능한가|어떻게)/,
      /화차.*(잡|빌|확보)/,
      /운송.*(맡기|의뢰)/,
    ],
    reason:
      "운송 신청·예약·배차는 저희가 만들지 않았습니다. 코레일이 구축 중인 플랫폼의 몫이고, 저희는 그 위에 얹는 진단 계층입니다.",
    instead: "그 구간의 물량과 운송거리, 돌아올 때 실을 화물이 있는지는 지금 바로 알려드릴 수 있습니다.",
  },
  {
    category: "realtime",
    // `지연` 단독으로 잡지 않는다 — "왜 이렇게 지연되나요"는 체류시간·X-factor가 답하는
    // 우리 핵심 질문이다. 실시간을 가리키는 말이 함께 있을 때만 범위 밖이다.
    patterns: [/실시간/, /지금.*(어디|위치|지연)/, /현재.*(위치|지연|운행)/, /몇 시에.*도착할까/],
    reason:
      "실시간 열차 위치·지연은 저희 데이터 밖입니다. 저희가 쓰는 것은 계획 시각표와 2025년 하반기 실적 통계뿐입니다.",
    instead: "계획 시각표 기준의 구간 소요시간과 정차 구성은 답해 드릴 수 있습니다.",
  },
  {
    category: "tariff",
    // `비용` 단독으로 잡지 않는다 — "사회적 비용", "혼잡 비용", "탄소 배출 비용"은
    // C1·C2가 계산하는 우리 핵심 주제다. 화주가 내는 돈을 가리킬 때만 범위 밖이다.
    // "얼마"도 단독으로 쓰지 않는다 — "물량이 얼마인가요"는 정상 질문이다.
    patterns: [
      /운임/,
      /요금/,
      /가격/,
      /견적/,
      /할인/,
      // "옮기면 … 사회적 비용이 줄어드나요"(핵심 편익 질문)가 걸리면 안 된다 —
      // 비용 바로 앞이 사회·환경·탄소·혼잡·사고면 화주가 내는 돈이 아니다.
      /(운송|운반|물류|배송|보내는|맡기는|옮기).*(?<!사회적 |사회 |환경 |탄소 |혼잡 |사고 )비용/,
      // `줄어들다`가 `들다`로 끝나서 "비용이 얼마나 줄어드나요"(정상)가 걸린다.
      // 비용이 **드는** 것과 **줄어드는** 것을 가르려면 앞 글자를 봐야 한다.
      /얼마.*(?<![줄늘]어)(들[까든지]|드[나니]|나옵)/,
    ],
    reason:
      "운임·요금은 저희 데이터에 없습니다. 저희가 보는 수송 실적에는 물량과 운송거리만 있고 금액이 없습니다.",
    instead:
      "전환 물량과 거리는 정확히 드릴 수 있고, 국토교통부 공식 기준값이 확정되면 사회적 편익 금액도 계산해 드립니다.",
  },
  {
    category: "raw-data",
    patterns: [/원본.*(주세|주실|줘|다운|파일|공유)/, /ktdb/i, /데이터.*(내려받|다운로드|전달)/],
    reason: "원본 데이터는 재배포가 금지돼 있어 드릴 수 없습니다.",
    instead: "집계 결과와 그 계산 근거는 화면에서 그대로 보여드립니다.",
  },
];

/** 구조적 범위 밖이면 사유를 돌려준다. 아니면 null — 정상 라우팅으로 보낸다. */
export function checkScope(question: string): OutOfScope | null {
  const q = question.trim();
  for (const rule of RULES) {
    if (rule.patterns.some((p) => p.test(q))) {
      const { category, reason, instead } = rule;
      return { category, reason, instead };
    }
  }
  return null;
}

/**
 * 거절문. 왜 못 하는지와 대신 무엇을 할 수 있는지를 반드시 함께 말한다.
 *
 * ⚠️ 이 문자열은 **LLM을 거치지 않고 화주에게 그대로 나간다.** 프롬프트의 어휘 규칙(#110)이
 *    적용되지 않으므로, 여기 쓰는 말은 직접 화주 언어로 골라야 한다.
 *    금지: 톤킬로 · 원단위 · 편방향 · O-D · stub · 영문 코드명.
 */
export function refusalText(scope: OutOfScope): string {
  return `${scope.reason}\n\n${scope.instead}`;
}
